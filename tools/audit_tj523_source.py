#!/usr/bin/env python3
"""Audit every TJ entrance against private original bytes and the private report.

Only executable relationships and summary counts are public. Neither ZIP is
copied into Git, and no player history is generated by this audit.
"""
import argparse
import hashlib
import json
from pathlib import Path
import zipfile

SOURCE_SHA = 'd5192c3c735ff95c6b181bf2d4d77448d8b562fdb28dbd43f897fa4eae1f4832'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-zip', required=True, type=Path)
    parser.add_argument('--report-zip', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    assert hashlib.sha256(args.source_zip.read_bytes()).hexdigest() == SOURCE_SHA
    checks = 0
    with zipfile.ZipFile(args.source_zip) as original, zipfile.ZipFile(args.report_zip) as report:
        assert original.testzip() is None and report.testzip() is None
        assert sum(n.startswith('content/') and n.endswith('.json') for n in original.namelist()) == 1065
        def evidence(name):
            return json.loads(report.read(next(n for n in report.namelist() if n.endswith('/'+name))))
        source_manifest = evidence('source_manifest.json')
        tables = {}
        for row in source_manifest['tables']:
            raw = original.read('content/'+row['table']+'.json')
            assert len(raw) == row['bytes'] and hashlib.sha256(raw).hexdigest() == row['sha256']
            assert f'{original.getinfo("content/"+row["table"]+".json").CRC:08x}' == row['crc32']
            values = json.loads(raw)['rows']
            assert len(values) == row['rows']
            tables[row['table']] = values
            checks += len(values)
        definitions = {int(x['ID']): x for x in tables['PlayerValueReturn']}
        histories = {int(x['HistoryType']): x for x in tables['TJCouponHistory']}
        bonuses = {int(x['ID']): x for x in tables['Bonus']}
        all_entrances = []
        actual = {}
        for link in tables['ItemBonus']:
            bonus = bonuses[int(link['BonusID'])]
            if bonus['BonusTypeID'] == 6604:
                all_entrances.append(link)
                policy = definitions[int(bonus['Value'])]
                if policy['BuffCardDeckID'] in (1, 2, 41, 98):
                    actual[int(link['ItemClassID'])] = (link, bonus, policy)
        entrances = evidence('card_coupon_item_input_season_expiry523.json')['card_items']
        assert len(actual) == len(entrances) == 139 and len(all_entrances) == 196
        assert len({x[2]['ID'] for x in actual.values()}) == 10 and len(definitions) == 18
        expiry = {'datetime': 0, 'legacy_raw': 0, 'unspecified': 0}
        seasons = 0
        for entry in entrances:
            item = entry['item']['raw']; identity = int(item['ID'])
            link, effect, policy = actual[identity]
            assert entry['return_definition']['raw'] == policy
            history = histories[policy['TJCouponHistoryType']]
            assert history['OwnerType'] == policy['OwnerTypeID']
            assert any(x['HistoryType'] == history['HistoryType'] and x['UnitID'] == 31 and x['Value'] == policy['BuffCardDeckID'] for x in tables['TJCouponHistoryMapping'])
            effects = [bonuses[int(x['BonusID'])] for x in tables['ItemBonus'] if x['ItemClassID'] == identity]
            delete = [x for x in effects if x['BonusTypeID'] == 492]
            if not delete: expiry['unspecified'] += 1
            elif delete[0]['Value'] == 0:
                assert delete[0]['BonusApplicationTypeID'] == 298
                assert any(x['ID'] == delete[0]['BonusApplicationTargetID'] for x in tables['DateTimes_Korean'])
                expiry['datetime'] += 1
            else: expiry['legacy_raw'] += 1
            season_effects = [x for x in effects if x['BonusTypeID'] == 11551]
            if season_effects:
                seasons += 1
                assert any(x['HistoryType'] == policy['TJCouponHistoryType'] and x['Season'] == season_effects[0]['Value'] for x in tables['TJCouponSeason'])
            checks += 1
        assert expiry == {'datetime':90,'legacy_raw':37,'unspecified':12} and seasons == 58
        # Scan every table for explicitly typed item references. Generic numeric
        # equality is deliberately not treated as an item foreign key.
        typed_references = {}
        source_row_count = 0
        coupon_ids = set(actual)
        item_units = {x['ID'] for x in tables['Unit'] if x['Name'] == 'ItemClassID'}
        item_bonus_types = {x['ID'] for x in tables['BonusType'] if x['UnitID'] in item_units}
        for name in original.namelist():
            if not name.startswith('content/') or not name.endswith('.json'):
                continue
            rows = json.loads(original.read(name)).get('rows', [])
            source_row_count += len(rows)
            fields = {}
            for row in rows:
                for field, value in row.items():
                    if field.endswith('ItemClassID') and isinstance(value, int) and value in coupon_ids:
                        fields[field] = fields.get(field, 0) + 1
                if name == 'content/Bonus.json' and row.get('BonusTypeID') in item_bonus_types and row.get('Value') in coupon_ids:
                    fields['Value[BonusType.Unit=ItemClassID]'] = fields.get('Value[BonusType.Unit=ItemClassID]', 0) + 1
            if fields:
                typed_references[name.removeprefix('content/').removesuffix('.json')] = fields
        runtime_root = Path(__file__).resolve().parents[1]
        option = json.loads((runtime_root/'data/cards/base508_option_awakening.json').read_text())
        economy = json.loads((runtime_root/'data/cards/base508_option_extensions.json').read_text())
        current_cards = {r['ID']:r for r in json.loads(original.read('content/BuffCard.json'))['rows']}
        current_groups = {r['ID']:r for r in json.loads(original.read('content/BuffCardOptionAwakenGroup.json'))['rows']}
        current_links = {r['ID']:r for r in json.loads(original.read('content/BuffCardOptionAwakenLevelBonus.json'))['rows']}
        current_values = {r['ID']:r for r in json.loads(original.read('content/BuffCardOptionAwakenValue.json'))['rows']}
        old_values = [r for group in economy['economy'].values() for r in group.values()]
        value_types = {r['ID']:r for r in json.loads(original.read('content/BuffCardOptionAwakenValueType.json'))['rows']}
        assert all(value_types[r['BuffCardOptionAwakenValueTypeID']]['Name'] == name for group in economy['economy'].values() for name, r in group.items())
        source_bonus_types = {r['ID']:r for r in tables['BonusType']}
        source_units = {r['ID']:r for r in tables['Unit']}
        effect_type_changes = sum(source_bonus_types.get(e['type']['ID']) != e['type'] or source_units.get(e['unit']['ID']) != e['unit'] for row in option['definitions'] for e in row['native_source']['effects'])
        assert effect_type_changes == 0, 'Changed semantic type metadata needs an explicit engine adapter'
        compatibility = {
            'engine_card_rows':len(option['definitions']), 'changed_effect_type_or_unit_metadata':effect_type_changes, 'all_cost_experience_type_names_verified':True,
            'changed_engine_card_rows':sum(current_cards.get(r['native_source']['card']['ID']) != r['native_source']['card'] for r in option['definitions']),
            'engine_group_rows':len(option['raw_groups']),
            'changed_engine_group_rows':sum(current_groups.get(r['ID']) != r for r in option['raw_groups']),
            'engine_cost_experience_rows':len(old_values),
            'changed_engine_cost_experience_rows':sum(current_values.get(r['ID']) != r for r in old_values),
            'engine_effect_link_rows':len(option['raw_level_links']),
            'changed_engine_effect_link_rows':sum(current_links.get(r['ID']) != r for r in option['raw_level_links']),
            'policy':'Runtime rejects changed latest523 inputs; it never overwrites source facts with the older engine.'}
        result = {'source_snapshot':'523', 'source_tables':1065,'option_engine_compatibility':compatibility, 'source_rows_scanned':source_row_count, 'direct_typed_coupon_references':typed_references, 'audited_tables':len(tables), 'table_rows_checked':checks-139, 'all_entrances':196,'card_entrances':139,'card_profiles':10,'all_profiles':18,'explicit_season_coupons':58,'expiry_encodings':expiry,'player_history_created':False,'execution_support':'separate Main/transaction tests required'}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps(result))

if __name__ == '__main__':
    main()
