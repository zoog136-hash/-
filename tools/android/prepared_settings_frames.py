def _plain_rgba_png(data):
    if len(data) < 33 or data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        return False
    width, height = struct.unpack_from(">II", data, 16)
    if not (0 < width <= 4096 and 0 < height <= 4096) or data[24:29] != bytes((8, 6, 0, 0, 0)):
        return False
    # Other color spaces, palettes, APNG and interlacing retain Godot/libpng's
    # complete interpretation. These verified byte-RGBA pages need no transform.
    pos = 8
    while pos + 12 <= len(data):
        size = struct.unpack_from(">I", data, pos)[0]
        kind = data[pos + 4:pos + 8]
        pos += size + 12
        if kind == b"IEND":
            return size == 0 and pos == len(data)
        if pos > len(data) or kind not in (b"IHDR", b"IDAT", b"pHYs"):
            return False
    return False


def _pixels(page, frame, image_api):
    def dimensions(key, count):
        v = frame.get(key)
        return isinstance(v, list) and len(v) == count and all(type(x) is int for x in v)

    if not (dimensions("rect", 4) and dimensions("source_rect", 4) and dimensions("source_size", 2)):
        return None
    x, y, w, h = frame["rect"]
    ox, oy, sw, sh = frame["source_rect"]
    width, height = frame["source_size"]
    rotated = frame.get("rotated", False)
    pw, ph = (h, w) if rotated else (w, h)
    if (min(x, y, ox, oy) < 0 or min(w, h, width, height) <= 0 or width * height > MAX_PIXELS
            or max(width, height) > 4096 or (sw, sh) != (w, h) or x + pw > page.width or y + ph > page.height
            or ox + w > width or oy + h > height):
        return None
    crop = page.crop((x, y, x + pw, y + ph))
    if rotated:
        crop = crop.transpose(image_api.Transpose.ROTATE_90)
    raw = bytearray(crop.tobytes())
    for i in range(0, len(raw), 4):
        scale = raw[i + 3] + 1
        if scale != 256:
            raw[i] = (raw[i] * scale) >> 8
            raw[i + 1] = (raw[i + 1] * scale) >> 8
            raw[i + 2] = (raw[i + 2] * scale) >> 8
    canvas = image_api.new("RGBA", (width, height))
    canvas.paste(image_api.frombytes("RGBA", (w, h), bytes(raw)), (ox, oy))
    return canvas.tobytes()


def add_to_package(root, manifest, section, members, scratch):
    """Pin the generated bytes in the selected section, outside original_ui.json."""
    # Repackaged directories may contain a sidecar from an older package.
    members[:] = [row for row in members if row[0] != BUNDLE]
    if "UI/Option/Option_All.csb" not in manifest.get("scenes", {}):
        return
    try:
        from PIL import Image
        try:
            from compression import zstd
            compress = zstd.compress
        except ImportError:
            from zstandard import ZstdCompressor
            compress = ZstdCompressor(level=3).compress
    except ImportError:
        print("Preparing settings frames requires Pillow and zstandard. Packaging the original UI pages.", file=sys.stderr)
        return
    payload = bytearray()
    ranges = {}
    atlases = {}
    for stem, names in FRAMES.items():
        atlas_name = f"UI/UI_Resource/{stem}.plist"
        member = f"UI/UI_Resource/{stem}.png"
        atlas = manifest.get("atlases", {}).get(atlas_name, {})
        if atlas.get("page") != member:
            continue
        source = manifest["files"].get(member, {})
        path = root / "originals" / member
        if not 0 < source.get("bytes", 0) <= 16 * 1024 * 1024:
            continue
        if path.stat().st_size != source["bytes"]:
            raise ValueError(f"UI atlas size changed: {member}")
        data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != source["sha256"]:
            raise ValueError(f"UI atlas SHA-256 changed: {member}")
        if not _plain_rgba_png(data):
            continue
        rows = {}
        with Image.open(io.BytesIO(data)) as page:
            if page.mode != "RGBA":
                continue
            for name in names:
                frame = atlas.get("frames", {}).get(name)
                raw = _pixels(page, frame, Image) if isinstance(frame, dict) else None
                if raw is None:
                    continue
                digest = hashlib.sha256(raw).hexdigest()
                if digest not in ranges:
                    packed = compress(raw)
                    if len(payload) + len(packed) > MAX_BUNDLE - 65536:
                        continue
                    ranges[digest] = [len(payload), len(packed)]
                    payload.extend(packed)
                rows[name] = {"geometry": [frame["rect"], frame["source_rect"], frame["source_size"],
                                           bool(frame.get("rotated", False))], "rgba_sha256": digest}
        if rows:
            atlases[atlas_name] = {"page": member, "source_sha256": source["sha256"], "frames": rows}
    if not atlases:
        return
    # This canonical digest is independent of the compressor, unrelated UI edits, and ZIP layout.
    catalog = json.dumps(atlases, separators=(",", ":"), sort_keys=True)
    index = json.dumps({"schema": SCHEMA, "manifest_sha256": section["manifest_sha256"],
                        "catalog": catalog, "ranges": ranges},
                       separators=(",", ":"), sort_keys=True).encode()
    if len(index) + 4 > 65536:
        raise ValueError("settings frame index exceeds runtime limit")
    output = scratch / BUNDLE
    data = struct.pack("<I", len(index)) + index + payload
    output.write_bytes(data)
    section["settings_frames_sha256"] = hashlib.sha256(data).hexdigest()
    members.append((BUNDLE, output, len(data)))
