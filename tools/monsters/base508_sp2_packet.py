"""Lossless portable wrapper for original SP2 source bytes.

Brotli is decoded during the build. The unchanged FE-SP2 bytes are gzip-packed
with the palette length established by the user's strict original decoder.
No PNG frames, atlases or replacement art are generated by this codec.
"""
import gzip,io,struct,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'lineagem_original'))
import brotli
import original_sp2

def source_body(raw,max_decoded_bytes=256*1024**2):
    """Cap FE input and accumulated Brotli output before normalization.

    Bounded output requires the compiler's Brotli streaming API. An older
    toolchain fails with a dependency message instead of an unbounded decode.
    No pixel, palette, direction, delta reference or coordinate is rewritten.
    """
    if not raw:raise ValueError('Empty source SP2')
    if max_decoded_bytes<1:raise ValueError('Invalid source SP2 decoded bound')
    if raw[0]==254:
        if len(raw)>max_decoded_bytes:raise ValueError('Source SP2 exceeds decoded bound')
        return raw
    decoder=brotli.Decompressor()
    if not hasattr(decoder,'can_accept_more_data'):
        raise ValueError('Compiler requires Brotli bounded streaming output API')
    decoded=io.BytesIO();position=0
    try:
        while position<len(raw) or not decoder.is_finished():
            if decoder.can_accept_more_data():
                if decoder.is_finished():raise ValueError('Trailing bytes after source Brotli stream')
                chunk=raw[position:position+64*1024];position+=len(chunk)
            else:chunk=b''
            part=decoder.process(chunk,output_buffer_limit=min(1024**2,max_decoded_bytes-decoded.tell()+1))
            if len(part)>max_decoded_bytes-decoded.tell():raise ValueError('Source SP2 exceeds decoded bound')
            decoded.write(part)
            if not chunk and not part and not decoder.is_finished():raise ValueError('Incomplete source Brotli stream')
    except brotli.error as error:raise ValueError('Invalid or truncated source Brotli stream')from error
    if not decoder.is_finished():raise ValueError('Incomplete source Brotli stream')
    body=decoded.getvalue()
    if not body or body[0]!=254:raise ValueError('Decoded source is not FE SP2')
    return body

def normalize(raw):
    body=source_body(raw)
    parsed=original_sp2.parse(body)
    normalized=b'LMSP1'+struct.pack('<H',len(parsed[0]))+body
    out=io.BytesIO()
    with gzip.GzipFile(fileobj=out,mode='wb',filename='',mtime=0,compresslevel=6) as z:z.write(normalized)
    return out.getvalue(),parsed

def geometry(parsed,bit,frame,cache=None):
    palette,mask,directions,_=parsed
    bits=[i for i in range(8) if mask&(1<<i)]
    if bit not in bits:raise ValueError(('Source direction absent',bit,mask))
    frames,blocks=directions[bits.index(bit)]
    if frame>=len(frames):raise ValueError(('Source frame absent',frame,len(frames)))
    minimum=None;maximum=None
    for a,b,t,index in frames[frame][1]:
        bx,by,values,rows=blocks[index]
        x0=24*(b+a-a//2)+bx;y0=12*(b-a//2)+by
        box=cache.get((bit,index)) if cache is not None else None
        if box is None:
            occupied=[(y,row) for y,row in enumerate(rows) if row]
            box=(min(x for _,row in occupied for x,c in row),min(y for y,row in occupied),max(x for _,row in occupied for x,c in row),max(y for y,row in occupied)) if occupied else ()
            if cache is not None:cache[(bit,index)]=box
        if not box:continue
        left,top,right,bottom=x0+box[0],y0+box[1],x0+box[2],y0+box[3]
        minimum=(left,top) if minimum is None else (min(minimum[0],left),min(minimum[1],top))
        maximum=(right,bottom) if maximum is None else (max(maximum[0],right),max(maximum[1],bottom))
    if minimum is None:return {'offset':[0,0],'pixel_size':[1,1],'empty':True}
    size=[maximum[0]-minimum[0]+1,maximum[1]-minimum[1]+1]
    if not (0<size[0]<4096 and 0<size[1]<4096):raise ValueError(('Source frame bounds',size))
    return {'offset':list(minimum),'pixel_size':size,'empty':False}
