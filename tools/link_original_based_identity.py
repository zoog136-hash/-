#!/usr/bin/env python3
"""Reuse reviewed motion only for an identical source and rendered presentation.

Linking is not gameplay approval. Each target still needs its own Main report.
Existing PNGs and SpriteFrames are never regenerated by this operation.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path

from PIL import Image

import build_animation_expansion as expansion
from import_original_based_motion import sharing_identity


AUTHORED_FIELDS = (
    "frames_path", "layout", "pixel_scale", "color_tint", "sprite_offset",
    "embedded_shadow", "authored_motion_weight", "hit_recoil", "action_hit_frames",
    "attack_hit_frame", "death_duration", "movement_fps",
)


def link(root, source_key, target_keys, apply=False):
    targets = {row["key"]: row for row in expansion.read(root / "data/animation_authoring_sources.json")["targets"]}
    document = expansion.read(root / "data/combat_animation_profiles.json")
    source = targets[source_key]
    profile = document["profiles"][source_key]
    frames_path = profile["frames_path"]
    prefix = "res://assets/actors/eight_direction/original_based/"
    if not frames_path.startswith(prefix) or ".." in Path(frames_path).parts:
        raise ValueError("Source must already use reviewed original-based motion")
    folder = (root / frames_path.removeprefix("res://")).parent
    proof = expansion.read(folder / "provenance.json")
    if source_key not in proof["target_keys"]:
        raise ValueError("Source identity is absent from the resource provenance")
    if proof.get("target_references", {}).get(source_key, proof["reference"]) != source["reference"]:
        raise ValueError("Source provenance no longer matches its reference")
    if proof.get("target_presentations", {}).get(source_key, proof["presentation_to_preserve"]) != source["presentation_to_preserve"]:
        raise ValueError("Source provenance no longer matches its presentation")
    bindings = [source] + [targets[key] for key in target_keys]
    for target in bindings:
        if sharing_identity(target, root=root) != sharing_identity(source, root=root):
            raise ValueError("Original image or rendered presentation differs: " + target["key"])
        reference = target["reference"]
        image = root / reference["path"].removeprefix("res://")
        if hashlib.sha256(image.read_bytes()).hexdigest() != reference["sha256"]:
            raise ValueError("Original reference SHA changed: " + str(image))
        with Image.open(image) as original:
            if list(original.size) != reference["image_size"]:
                raise ValueError("Original reference dimensions changed")
        current_frames = document["profiles"].get(target["key"], {}).get("frames_path", "")
        if current_frames and current_frames != frames_path:
            raise ValueError("Do not replace an existing motion binding: " + target["key"])
    before = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
              for path in folder.iterdir() if path.suffix in {".png", ".tres"}}
    for target in bindings[1:]:
        key = target["key"]
        current = copy.deepcopy(document["profiles"].get(key, {}))
        if "prior_visual_profile" not in current:
            current["prior_visual_profile"] = copy.deepcopy(current) or None
        current.update({field: copy.deepcopy(profile[field]) for field in AUTHORED_FIELDS})
        current.update(name=target["name"], authoring_reference=target["reference"]["path"])
        document["profiles"][key] = current
        if key not in proof["target_keys"]:
            proof["target_keys"].append(key)
        proof.setdefault("target_references", {})[key] = target["reference"]
        proof.setdefault("target_presentations", {})[key] = target["presentation_to_preserve"]
    if apply:
        expansion.save(folder / "provenance.json", proof)
        expansion.save_profiles(root / "data/combat_animation_profiles.json", document)
    after = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
             for path in folder.iterdir() if path.suffix in {".png", ".tres"}}
    if before != after:
        raise AssertionError("Existing artwork or SpriteFrames changed")
    return {"source_key": source_key, "targets": target_keys, "frames_path": frames_path,
            "applied": apply, "existing_resource_sha256": before,
            "actual_gameplay": "not_run_by_linker"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--source-key", required=True)
    parser.add_argument("--target-key", action="append", required=True)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    print(json.dumps(link(args.root.resolve(), args.source_key, args.target_key, args.apply), ensure_ascii=False))


if __name__ == "__main__":
    main()
